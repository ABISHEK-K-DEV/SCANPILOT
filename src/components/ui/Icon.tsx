export type IconName = keyof typeof ICONS;

interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
  /** Line weight; defaults to a crisp 1.85 that scales with size. */
  strokeWidth?: number;
}

/** Decorative by default; give the parent control an accessibilityLabel. */
export function Icon({ name, size = 22, color, strokeWidth }: IconProps) {
  const theme = useAppTheme();
  const entry: { c: LucideIcon; fill?: boolean } = ICONS[name];
  const Glyph = entry.c;
  const tint = color ?? theme.colors.text;
  return (
    <Glyph
      size={size}
      color={tint}
      fill={entry.fill ? tint : 'none'}
      strokeWidth={strokeWidth ?? (size <= 16 ? 2 : 1.85)}
      accessibilityElementsHidden
      importantForAccessibility="no"
    />
  );
}
