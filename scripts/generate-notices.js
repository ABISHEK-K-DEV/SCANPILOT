#!/usr/bin/env node
/**
 * Generates src/legal/thirdPartyNotices.generated.ts: the licence text of every
 * production dependency (MIT/BSD/Apache notices must ship with the app). The
 * file is bundled into the app — satisfying the notice requirement — but no
 * screen displays it. Identical licence texts are stored once.
 *
 *   npm run notices          (regenerate)
 *   npm run notices -- --check   (CI: fail if the committed file is stale)
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const outFile = path.join(root, 'src/legal/thirdPartyNotices.generated.ts');
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

/** Native SDKs bundled by Gradle (not npm) — notices kept here by hand. */
const NATIVE = [
  { name: 'Google ML Kit (text recognition, document scanner)', license: 'Google APIs Terms of Service', text: 'Used under the ML Kit Terms of Service: https://developers.google.com/ml-kit/terms' },
  { name: 'AndroidX CameraX', license: 'Apache-2.0', text: 'Copyright The Android Open Source Project. Licensed under the Apache License, Version 2.0: https://www.apache.org/licenses/LICENSE-2.0' },
  { name: 'PDFium / PdfiumAndroidKt / AndroidPdfViewer', license: 'BSD-3-Clause / Apache-2.0', text: 'PDFium: Copyright 2014 The PDFium Authors (BSD-3-Clause). PdfiumAndroidKt and AndroidPdfViewer: Apache License 2.0.' },
  { name: 'Inter typeface', license: 'SIL Open Font License 1.1', text: 'Copyright 2016 The Inter Project Authors (https://github.com/rsms/inter). Licensed under the SIL Open Font License, Version 1.1: https://openfontlicense.org' },
];

function readJson(file) {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch {
    return null;
  }
}

function resolvePackage(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = path.join(dir, 'node_modules', name, 'package.json');
    if (fs.existsSync(candidate)) return candidate;
    const parent = path.dirname(dir);
    if (parent === dir) return null;
    dir = parent;
  }
}

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && pkg.license.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type || l).join(' OR ');
  return 'UNKNOWN';
}

const rootPkg = readJson(path.join(root, 'package.json'));
const seen = new Map();
const queue = Object.keys(rootPkg.dependencies || {}).map((name) => [name, root]);
while (queue.length) {
  const [name, from] = queue.shift();
  const file = resolvePackage(name, from);
  if (!file || seen.has(file)) continue;
  const pkg = readJson(file);
  if (!pkg) continue;
  const dir = path.dirname(file);
  const licFile = fs.readdirSync(dir).find((f) => LICENSE_FILE.test(f));
  const text = licFile ? fs.readFileSync(path.join(dir, licFile), 'utf8').replace(/\r\n/g, '\n').trim() : '';
  seen.set(file, { name: pkg.name, version: pkg.version, license: licenseOf(pkg), text });
  for (const dep of Object.keys({ ...(pkg.dependencies || {}), ...(pkg.optionalDependencies || {}) })) queue.push([dep, dir]);
}

const texts = [];
const index = new Map();
const packages = [...seen.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(({ name, version, license, text }) => {
    let t = -1;
    if (text) {
      if (!index.has(text)) {
        index.set(text, texts.length);
        texts.push(text);
      }
      t = index.get(text);
    }
    return [name, version, license, t];
  });

const body = `// GENERATED by scripts/generate-notices.js — do not edit. Run \`npm run notices\`.
// Licence notices of ScanPilot's third-party components. Bundled with the app
// (as the licences require) but not shown in the UI.

/** [name, version, SPDX licence, index into LICENSE_TEXTS or -1] */
export const THIRD_PARTY_PACKAGES: readonly (readonly [string, string, string, number])[] = ${JSON.stringify(packages)};

export const NATIVE_COMPONENTS: readonly { name: string; license: string; text: string }[] = ${JSON.stringify(NATIVE)};

export const LICENSE_TEXTS: readonly string[] = ${JSON.stringify(texts)};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (current !== body) {
    console.error('src/legal/thirdPartyNotices.generated.ts is out of date. Run `npm run notices`.');
    process.exit(1);
  }
  console.log(`Notices up to date (${packages.length} packages, ${texts.length} distinct licence texts).`);
} else {
  fs.writeFileSync(outFile, body);
  console.log(`Wrote ${path.relative(root, outFile)}: ${packages.length} packages, ${texts.length} distinct licence texts, ${(body.length / 1024).toFixed(0)} KB.`);
}
